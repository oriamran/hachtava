H.vocalFor = function(t){
  if(!t || /[\u05B0-\u05C7]/.test(t)) return t;                 /* כבר מנוקדת */
  const key = String(t).replace(/\s+/g, ' ').trim();
  if(!/[\u05D0-\u05EA]/.test(key)) return t;
  const sig = H.state.packs.length + ':' + H.state.packs.reduce((a, p) => a + p.list.length, 0) + ':' + H.state.pack;
  if(H._vm === undefined || H._vmSig !== sig){
    const m = new Map(), add = w => { const s = H.strip(String(w)).replace(/\s+/g, ' ').trim(); if(s !== w && /[\u05B0-\u05C7]/.test(w) && !m.has(s)) m.set(s, w.replace(/\s+/g, ' ').trim()); };
    const cur = H.pack && H.pack(); if(cur) cur.list.forEach(add);                       /* הרשימה הנוכחית קודמת */
    H.state.packs.forEach(p => p.list.forEach(add));
    (H.LIB || []).forEach(tier => tier.topics.forEach(tp => tp.words.forEach(add)));
    Object.keys(H.TTS_VOCAL).forEach(k => { if(!m.has(k)) m.set(k, H.TTS_VOCAL[k]); });
    H._vm = m; H._vmSig = sig;
  }
  return H._vm.get(key) || t;
};
