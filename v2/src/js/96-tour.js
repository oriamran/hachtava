H.tour = {i: 0};

H.startTour = function(){ H.tour.i = 0; H.renderTour(); H.show('tour'); };
H.renderTour = function(){
  const n = H.TOUR.length, s = H.TOUR[H.tour.i];
  H.$('tour-e').textContent = s.e;
  H.$('tour-t').textContent = s.t;
  H.$('tour-p').textContent = s.p;
  H.$('tour-dots').innerHTML = H.TOUR.map((_, i) => '<i class="' + (i === H.tour.i ? 'on' : '') + '"></i>').join('');
  H.$('tour-prev').style.visibility = H.tour.i ? 'visible' : 'hidden';
  H.$('tour-next').textContent = H.tour.i === n - 1 ? 'יאללה, מתחילים! 🚀' : 'הבא';
  H.$('tour-skip').style.visibility = H.tour.i === n - 1 ? 'hidden' : 'visible';
};
H.nextTour = function(){
  H.sfx.tap();
  if(H.tour.i >= H.TOUR.length - 1) return H.endTour();
  H.tour.i++; H.renderTour();
};
H.prevTour = function(){ H.sfx.tap(); if(H.tour.i) { H.tour.i--; H.renderTour(); } };
H.endTour = function(){
  H.state.tour = true; H.save();
  H.refresh(); H.show('home');
};

